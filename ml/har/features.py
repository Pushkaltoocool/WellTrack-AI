"""
WellTrack AI - HAR feature extraction (reference implementation).

This module is the single source of truth for the feature definitions used by the
deployed activity model. The TypeScript port lives in
src/services/ml/harFeatures.ts and MUST stay numerically identical; parity is
verified by tests/harParity.test.ts using fixtures generated by train_har.py.

Input: one window of 128 samples (2.56 s at 50 Hz) for six channels, in this order:
    total_acc_x, total_acc_y, total_acc_z   (units: g, gravity included, Android sign convention)
    body_gyro_x, body_gyro_y, body_gyro_z   (units: rad/s)

Pipeline (per window):
    1. 3-point median filter on each of the six channels (edges keep the original value).
    2. Derive acceleration magnitude |a| and gyroscope magnitude |w|  -> 8 signals.
    3. Per signal: mean, std, min, max, median, iqr, mad, rms, jerk_std   (9 x 8 = 72)
    4. Pearson correlations acc xy/xz/yz and gyro xy/xz/yz            (6)
    5. Spectral features for |a| and |w|: dominant frequency and
       magnitude-weighted mean frequency of the mean-removed signal    (2 x 2 = 4)
    Total: 82 features.

All definitions avoid library-specific behaviour so they can be ported exactly:
    std  = population standard deviation (ddof = 0)
    percentile = linear interpolation between closest ranks (numpy default "linear")
    mad  = mean absolute deviation around the mean
    jerk_std = std of first difference multiplied by the sampling rate (units / s)
    DFT  = naive real DFT over bins 1..N/2 (DC excluded)
"""
from __future__ import annotations

import math
from typing import List

import numpy as np

SAMPLE_RATE_HZ = 50.0
WINDOW_SIZE = 128
WINDOW_STEP = 64

CHANNELS = ["acc_x", "acc_y", "acc_z", "gyro_x", "gyro_y", "gyro_z"]
SIGNALS = CHANNELS + ["acc_mag", "gyro_mag"]
STATS = ["mean", "std", "min", "max", "median", "iqr", "mad", "rms", "jerk_std"]
CORR_PAIRS = [
    ("acc_x", "acc_y"), ("acc_x", "acc_z"), ("acc_y", "acc_z"),
    ("gyro_x", "gyro_y"), ("gyro_x", "gyro_z"), ("gyro_y", "gyro_z"),
]
SPECTRAL_SIGNALS = ["acc_mag", "gyro_mag"]
SPECTRAL_STATS = ["dom_freq", "mean_freq"]


def feature_names() -> List[str]:
    names = [f"{sig}_{stat}" for sig in SIGNALS for stat in STATS]
    names += [f"corr_{a}_{b}" for a, b in CORR_PAIRS]
    names += [f"{sig}_{stat}" for sig in SPECTRAL_SIGNALS for stat in SPECTRAL_STATS]
    return names


def median3(x: np.ndarray) -> np.ndarray:
    out = x.copy()
    n = len(x)
    for i in range(1, n - 1):
        a, b, c = x[i - 1], x[i], x[i + 1]
        out[i] = max(min(a, b), min(max(a, b), c))
    return out


def percentile_linear(sorted_x: np.ndarray, q: float) -> float:
    n = len(sorted_x)
    pos = (n - 1) * q
    lo = math.floor(pos)
    hi = min(lo + 1, n - 1)
    frac = pos - lo
    return float(sorted_x[lo] + (sorted_x[hi] - sorted_x[lo]) * frac)


def _stats(x: np.ndarray) -> List[float]:
    n = len(x)
    mean = float(np.sum(x) / n)
    dev = x - mean
    std = math.sqrt(float(np.sum(dev * dev) / n))
    s = np.sort(x)
    median = percentile_linear(s, 0.5)
    iqr = percentile_linear(s, 0.75) - percentile_linear(s, 0.25)
    mad = float(np.sum(np.abs(dev)) / n)
    rms = math.sqrt(float(np.sum(x * x) / n))
    d = np.diff(x) * SAMPLE_RATE_HZ
    dm = float(np.sum(d) / len(d))
    jerk_std = math.sqrt(float(np.sum((d - dm) ** 2) / len(d)))
    return [mean, std, float(s[0]), float(s[-1]), median, iqr, mad, rms, jerk_std]


def _corr(a: np.ndarray, b: np.ndarray) -> float:
    n = len(a)
    da = a - np.sum(a) / n
    db = b - np.sum(b) / n
    den = math.sqrt(float(np.sum(da * da)) * float(np.sum(db * db)))
    if den < 1e-12:
        return 0.0
    return float(np.sum(da * db)) / den


def _spectral(x: np.ndarray) -> List[float]:
    n = len(x)
    xc = x - np.sum(x) / n
    idx = np.arange(n)
    best_k, best_mag = 1, -1.0
    weighted, total = 0.0, 0.0
    for k in range(1, n // 2 + 1):
        ang = 2.0 * math.pi * k * idx / n
        re = float(np.sum(xc * np.cos(ang)))
        im = float(np.sum(xc * np.sin(ang)))
        mag = math.sqrt(re * re + im * im)
        if mag > best_mag:
            best_mag, best_k = mag, k
        freq = k * SAMPLE_RATE_HZ / n
        weighted += freq * mag
        total += mag
    dom = best_k * SAMPLE_RATE_HZ / n
    mean_freq = weighted / total if total > 1e-12 else 0.0
    return [dom, mean_freq]


def extract_features(window: np.ndarray) -> np.ndarray:
    """window: array of shape (6, 128) in CHANNELS order."""
    assert window.shape == (6, WINDOW_SIZE), window.shape
    ch = [median3(np.asarray(window[i], dtype=np.float64)) for i in range(6)]
    acc_mag = np.sqrt(ch[0] ** 2 + ch[1] ** 2 + ch[2] ** 2)
    gyro_mag = np.sqrt(ch[3] ** 2 + ch[4] ** 2 + ch[5] ** 2)
    signals = {name: ch[i] for i, name in enumerate(CHANNELS)}
    signals["acc_mag"] = acc_mag
    signals["gyro_mag"] = gyro_mag

    feats: List[float] = []
    for sig in SIGNALS:
        feats += _stats(signals[sig])
    for a, b in CORR_PAIRS:
        feats.append(_corr(signals[a], signals[b]))
    for sig in SPECTRAL_SIGNALS:
        feats += _spectral(signals[sig])
    return np.array(feats, dtype=np.float64)


def extract_batch(windows: np.ndarray) -> np.ndarray:
    """windows: (n, 6, 128)."""
    return np.stack([extract_features(w) for w in windows])
